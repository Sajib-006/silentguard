"""Write numbers_p1.tex (the \\num{...} macros of the 2026-11-24 log analyses) from the analysis JSON files.

    python make_numbers_p1.py <dir with the json files> <out dir>

No number is typed by hand: every macro is computed here from phase1_stats.json, abstain_split.json,
retail_natural_silent.json and realapi_by_domain.json.
"""
import json
import sys
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])
P = json.loads((src / "phase1_stats.json").read_text())
AS = json.loads((src / "abstain_split.json").read_text())
RN = json.loads((src / "retail_natural_silent.json").read_text())
DOM = json.loads((src / "realapi_by_domain.json").read_text())
K = {}

# warning arm: seeing is not acting
f = P["funnel"]["advisory_nonum"]
faulted = sum(v["faulted"] for v in f.values())
fired = sum(v.get("fired", 0) for v in f.values())
wrong = sum(v.get("fired_wrong_num", 0) for v in f.values())
confs = [v["conf_wrong_after_flag"] for v in f.values() if v.get("conf_wrong_after_flag") is not None]
K["p1-faulted-n"] = f"{faulted:,}".replace(",", "{,}")
K["p1-fired-n"] = f"{fired:,}".replace(",", "{,}")
K["p1-fired"] = f"{100 * fired / faulted:.1f}"
K["p1-wrongafter"] = f"{100 * wrong / fired:.1f}"
K["p1-conf-min"], K["p1-conf-max"] = f"{min(confs):.2f}", f"{max(confs):.2f}"

# who abstains under SilentGuard
pf = AS["pooled_faulted_pct"]
K["as-agent"], K["as-harness"], K["as-gate"] = (f"{pf[k]:.1f}" for k in ("unknown_agent", "unknown_harness", "any_gate_rejection"))
gate = {m: v["any_gate_rejection"] for m, v in AS["per_model"].items()}
K["as-gate-max"], K["as-gate-min"] = f"{max(gate.values()):.0f}", f"{min(gate.values()):.0f}"


# paired run-level tests (differences reported as positive drops)
def pair(key, name):
    v = P["paired"][key]
    lo, hi = v["ci95_task_bootstrap"]
    K[f"pr-{name}"] = f"{-v['diff_points']:.1f}"
    K[f"pr-{name}-lo"], K[f"pr-{name}-hi"] = f"{-hi:.1f}", f"{-lo:.1f}"
    K[f"pr-{name}-n"] = f"{v['n_pairs']:,}".replace(",", "{,}")


pair("sgp_vs_none", "none"); pair("sgp_vs_advisory_nonum", "warn"); pair("sgp_vs_advisory_nonum_abstain", "abst")
pair("sgp_vs_enforce2", "enf"); pair("sgp_vs_judge_block", "jb"); pair("sgp_vs_repair3", "rep")

# cost: faulted runs where the fault leaves the true count unchanged
fa = P["false_alarm"]
K["fa-n"] = str(fa["none"]["pooled"]["n"])
for arm, name in (("none", "none"), ("sgp", "sgp"), ("enforce2", "enf")):
    p = fa[arm]["pooled_pct"]
    K[f"fa-{name}-correct"], K[f"fa-{name}-unknown"] = f"{p.get('correct', 0):.1f}", f"{p.get('abstain', 0):.1f}"
K["fa-none-affected-wrong"] = f"{fa['none']['affected_pooled_pct']['wrong_num']:.1f}"

# natural rate on real APIs, right documentation
n = P["natural"]["pooled"]
K["nat-runs"], K["nat-undoc"], K["nat-wrong"] = str(n["runs"]), str(n["runs_with_undocumented_param"]), str(n["wrong_num"])

# the silent failure nobody planted (retail, fault-free tasks)
r = RN["pooled"]
K["rn-n"], K["rn-ignored"], K["rn-reported"] = str(r["n"]), str(r["api_ignored_body"]), str(r["ignored_wrong_num"])
K["rn-pct"] = f"{100 * r['api_ignored_body'] / r['n']:.1f}"
K["rn-sgp-wrong"], K["rn-sgp-unknown"], K["rn-sgp-correct"] = str(r["sgp_wrong_num"]), str(r["sgp_abstain"]), str(r["sgp_correct"])
K["rn-models"] = str(sum(1 for v in RN["per_model"].values() if v.get("api_ignored_body", 0) > 0))

# real APIs by domain
for g, v in DOM["results"].items():
    name = "bio" if g.startswith("biomedical") else ("div" if g.startswith("biodiversity") else "gen")
    K[f"dom-{name}-none"], K[f"dom-{name}-sgp"] = f"{v['none']['wrong']:.1f}", f"{v['sgp']['wrong']:.1f}"
    K[f"dom-{name}-spec"] = f"{v['schema']['wrong']:.1f}"

lines = ["% GENERATED by make_numbers_p1.py from the 2026-11-24 analysis JSON files. Do not edit by hand."]
lines += [f"\\expandafter\\def\\csname num@{k}\\endcsname{{{v}}}" for k, v in sorted(K.items())]
(out / "numbers_p1.tex").write_text("\n".join(lines) + "\n")
for k, v in sorted(K.items()):
    print(f"{k:24s} {v}")
